#!/usr/bin/env python3
"""Embed truma_heater/web/index.html into truma_heater/web_ui.h (served from flash).

  python3 firmware/heater/tools/embed_web.py           write web_ui.h
  python3 firmware/heater/tools/embed_web.py --check   compare only, exit code 1 if outdated (CI)

Uses only the Python standard library (no venv needed). The shared design block in the page
is kept up to date by tools/common/sync_common.py; run that first.
"""
import argparse
import pathlib
import sys

SKETCH = pathlib.Path(__file__).resolve().parent.parent / "truma_heater"
SRC = SKETCH / "web" / "index.html"
DST = SKETCH / "web_ui.h"
DELIM = "rawliteral"   # docs/gen_mockup.py reads the page between these delimiters


def render() -> str:
    html = SRC.read_text(encoding="utf-8")
    if f'){DELIM}"' in html:
        raise SystemExit("index.html contains the raw string delimiter, change DELIM")
    return ("// Single page web UI (served from flash, no filesystem upload needed).\n"
            "// Generated by tools/embed_web.py from web/index.html - do not edit by hand.\n"
            "#pragma once\n\n"
            f'static const char INDEX_HTML[] = R"{DELIM}({html}){DELIM}";\n')


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare only, do not write")
    args = ap.parse_args()
    out = render()
    if args.check:
        if not DST.is_file() or DST.read_text(encoding="utf-8") != out:
            print("web_ui.h is outdated: run python3 firmware/heater/tools/embed_web.py")
            return 1
        return 0
    DST.write_text(out, encoding="utf-8")
    print(f"{DST.name}: {len(out.encode('utf-8'))} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
