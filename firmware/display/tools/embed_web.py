#!/usr/bin/env python3
"""Embed web/index.html into web_ui.h (PROGMEM raw string).

Run after editing the web page:
    python3 tools/embed_web.py
Uses only the Python standard library.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / "_arduino" / "camper_display"
SRC = ROOT / "web" / "index.html"
DST = ROOT / "web_ui.h"
DELIM = "WEBUI"


def main() -> int:
    html = SRC.read_text(encoding="utf-8")
    if f'){DELIM}"' in html:
        print("index.html contains the raw string delimiter, change DELIM", file=sys.stderr)
        return 1
    out = (
        "#pragma once\n"
        "// Generated by tools/embed_web.py from web/index.html - do not edit by hand\n"
        "#include <Arduino.h>\n\n"
        f'const char WEB_UI[] PROGMEM = R"{DELIM}({html}){DELIM}";\n'
    )
    DST.write_text(out, encoding="utf-8")
    print(f"{DST.name}: {len(html.encode('utf-8'))} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
